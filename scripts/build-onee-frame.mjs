/**
 * Bake Onee's resting frame into a plain TypeScript module.
 *
 * The avatar's shape is computed, not drawn: every path in it comes out of
 * @bible-strong/avatar-core's geometry solver. That solver plus the animation
 * runtime and the 24KB definition it reads is far too much to put in the
 * critical bundle for a decorative character, and it is far too much to run
 * during the static prerender on every route either.
 *
 * So the resting pose — the one thing that has to exist in the server HTML —
 * is precomputed here into `src/data/oneeFrame.ts`. The component renders that
 * synchronously (no dependency on avatar-core at all), which means the
 * prerendered page ships a complete avatar, a visitor with no JS still sees
 * one, and hydration has nothing to reconcile. The animation runtime is a
 * dynamic import that arrives later and mutates the same SVG nodes in place.
 *
 * This runs from `prebuild`, so the baked frame cannot drift from the
 * definition: every build regenerates it. It is committed anyway so that
 * `npm run dev` works on a clean checkout without a build step first.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { renderAvatarDefinition } from "@bible-strong/avatar-core";

const root = new URL("../", import.meta.url);
const defPath = new URL("src/data/onee.avatar.json", root);
const outPath = new URL("src/data/oneeFrame.ts", root);

const definition = JSON.parse(readFileSync(defPath, "utf8"));

// `neutral` rather than the first frame of an animation: the resting pose is
// what the avatar should hold if the runtime never arrives, and it is the pose
// every animation transitions out of.
const scene = renderAvatarDefinition(definition, "neutral");
const { geometry, colors } = scene;

const j = (value) => JSON.stringify(value);

const file = `// Generated by scripts/build-onee-frame.mjs from src/data/onee.avatar.json.
// Do not edit by hand — \`npm run build\` regenerates it.
//
// Onee's resting pose, precomputed so the prerendered HTML carries a finished
// avatar without pulling the geometry solver into the client bundle.

export type OneeFrame = {
  headPath: string;
  leftPath: string;
  rightPath: string;
  leftVisible: boolean;
  rightVisible: boolean;
  backPaths: readonly string[];
  frontPaths: readonly string[];
  colors: { body: string; eyes: string };
};

export const oneeFrame: OneeFrame = {
  headPath: ${j(geometry.headPath)},
  leftPath: ${j(geometry.leftPath)},
  rightPath: ${j(geometry.rightPath)},
  leftVisible: ${j(geometry.leftVisible)},
  rightVisible: ${j(geometry.rightVisible)},
  backPaths: ${j(geometry.backPaths)},
  frontPaths: ${j(geometry.frontPaths)},
  colors: { body: ${j(colors.body)}, eyes: ${j(colors.eyes)} },
};

// The viewBox the solver emits paths in. Fixed by avatar-core, not by us.
export const ONEE_VIEWBOX = "-150 -150 300 300";
`;

const previous = (() => {
  try {
    return readFileSync(outPath, "utf8");
  } catch {
    return null;
  }
})();

if (previous !== file) {
  writeFileSync(outPath, file);
  console.log(
    `build-onee-frame: wrote ${fileURLToPath(outPath).replace(fileURLToPath(root), "")} (${file.length} bytes)`,
  );
} else {
  console.log("build-onee-frame: up to date");
}
